#   • Felfedezők és híres hajók: felfedezők, hajóik, útjaik célja, valamint más híres hajók
#   • Űrszondák: a 20–21. század nevezetes űrszondái és küldetéseik
#
# A zavaró opciók kézzel válogatottak: mindig ugyanabból a kategóriából
# (hajó a hajó mellé, szonda a szonda mellé, cél a cél mellé), és lehetőleg
# „közeli” tévedések – pl. ugyanannak a flottának egy másik hajója.
#
# Sorformátum: (kérdés, helyes válasz, [3 zavaró opció], magyarázat, [beírásnál elfogadott alakok])

import random

_rng = random.Random(1492)


def _build(rows, topic):
    out = []
    for row in rows:
        question, answer, wrong, explanation = row[:4]
        accept = row[4] if len(row) > 4 else []
        assert len(wrong) == 3 and answer not in wrong, question
        opts = [answer] + list(wrong)
        _rng.shuffle(opts)
        out.append({
            "question": question,
            "options": opts,
            "correct": opts.index(answer),
            "explanation": explanation,
            "topic": topic,
            "accept": list(accept),
        })
    return out


